// Instrument the live main.js loop, retaining input, overlays and DOM interface work.
import { releaseGame } from './release-fixtures.mjs';
import { performanceFixture, ecosystemCounts, ecosystemSignature } from './performance-fixtures.mjs';
import { PLANTS } from '../js/data/plants.js';
import { biome } from '../js/biome.js';
import { settings } from '../js/settings.js';
import { mulberry32 } from '../js/rng.js';
import { PERFORMANCE_BENCHMARK_REVISION, percentile, PerformancePhases, renderObjectCounts, withoutVegetation } from '../js/performance.js';

export async function measureGameplay({ map, scene = 'ecosystem', density, optimizations, zoom,
  isolation = 'normal', quality = 'fast', motion = true, samples = 60, warmup = 30, speed = density ? 1 : 3 }) {
  if (!['normal', 'simulation-off', 'vegetation-hidden'].includes(isolation)) throw new Error('Unknown isolation mode');
  if (!Number.isInteger(samples) || samples < 1 || !Number.isInteger(warmup) || warmup < 1) throw new Error('Invalid sample counts');
  const { game, renderer, ui } = window.secondGrowth;
  if (window.secondGrowth.diagnostics) throw new Error('Run benchmarks in the isolated page without ?perf=1 so CPU probes do not overlap');
  const randomBefore = Math.random, simulationRandom = mulberry32(20261013);
  const fixture = density ? performanceFixture(map, density) : releaseGame(map, scene);
  if (!game.restoreSave(fixture.game.saveData())) throw new Error('Gameplay fixture restore failed');
  // The surrounding forest is regenerated by save restoration, not serialized.
  for (const field of ['tree', 'treeG', 'shrub', 'ground']) game.border[field].set(fixture.game.border[field]);
  game.speed = speed; game.autosave = false;
  if (ui.modalOpen) ui.closeModal();
  ui.afterNewGame(); ui.refreshTop(true);
  renderer.applySettings({ ...settings, quality, qualityChosen: true, shadows: true, wind: true, weather: true, dayCycle: false });
  if (optimizations) renderer.flora.setOptimizations(optimizations);
  // (fixed work to measure: full resolution and shadows, whatever the automatic resolution did
  // while loading)
  renderer.autoRes = false; renderer.zoom = zoom ?? (scene === 'herd' ? .65 : .7);
  renderer.setRes(1); renderer.sun.castShadow = true; renderer.shadowsDropped = false;
  renderer.zoomGoal = null; renderer.fly = null;
  renderer.centerOn(...fixture.center); renderer.updateCamera(); renderer.shadowState = null;
  const initial = ecosystemCounts(game);
  const initialSignature = ecosystemSignature(game);
  const diagnosticTime = renderer.diagnosticTime;
  renderer.diagnosticTime = performance.now();
  const clockOrigin = renderer.diagnosticTime;
  renderer.time = 0; renderer.todClock = 0; renderer.lightReady = false;
  renderer.lastFlora = -Infinity; renderer.lastSurface = -Infinity;
  renderer.particles = []; renderer.weatherParticles = []; renderer.flies = []; renderer.eggs = [];
  // Settle startup independently of the measured ecology sequence. This includes
  // model/shader construction and first-frame full rebuilds in every mode.
  game.speed = 0; renderer.draw(game, ui.state, 0); game.speed = speed;
  const original = { update: game.update, draw: renderer.draw, frame: ui.frame, render: renderer.gl.render };
  const gl = renderer.gl.getContext(), rows = [], gaps = [], probes = new PerformancePhases(game, renderer);
  let n = 0, started, previous, simMs, renderMs, cpuRenderMs, submitMs, isolationMs;
  const began = performance.now();
  try {
    renderer.gl.render = function (...args) {
      const at = performance.now();
      let drawMs = 0;
      const draw = () => {
        const drawAt = performance.now();
        try { return original.render.apply(this, args); }
        finally { drawMs += performance.now() - drawAt; }
      };
      try {
        return isolation === 'vegetation-hidden'
          ? withoutVegetation(renderer.flora, draw, !!biome.look.underwater) : draw();
      } finally {
        submitMs += drawMs;
        if (isolation === 'vegetation-hidden') isolationMs += performance.now() - at - drawMs;
      }
    };
    await new Promise((resolve, reject) => {
      // (a stall guard only: CI's software compositor presents about one frame a second, so the
      // 90 frames take 90-120 s there; frame-work limits are asserted separately)
      const timeout = setTimeout(() => reject(new Error('Live gameplay measurement timed out')), 240000);
      const fail = error => { clearTimeout(timeout); reject(error); };
      game.update = function () {
        try {
          probes.reset(); submitMs = isolationMs = 0; started = performance.now();
          renderer.diagnosticTime = clockOrigin + (n + 1) * 1000 / 30;
          if (previous != null && n >= warmup) gaps.push(started - previous); previous = started;
          if (scene === 'planting' && n % 12 === 0) {
            const i = game.world.idx(42 + Math.floor(n / 12), 32);
            ui.actions.apply('clear', [i], { random: game.rng });
            const p = PLANTS.find(p => p?.native && p.layer === 0 && !p.invasive);
            if (p) ui.actions.apply('plant_' + p.key, [i], { random: () => 0 });
          }
          renderer.target.x = fixture.center[0] + (motion ? Math.sin(n / 20) * 3 : 0);
          renderer.updateCamera();
          const at = performance.now();
          if (isolation !== 'simulation-off') {
            const drawingRandom = Math.random; Math.random = simulationRandom;
            try { original.update.call(this, 1 / 30); }
            finally { Math.random = drawingRandom; }
          }
          simMs = performance.now() - at;
        } catch (error) { fail(error); throw error; }
      };
      renderer.draw = function (g, state) {
        try {
          const at = performance.now(); original.draw.call(this, g, state, 1 / 30);
          cpuRenderMs = performance.now() - at;
          gl.finish(); renderMs = performance.now() - at;
        } catch (error) { fail(error); throw error; }
      };
      ui.frame = function (...args) {
        try {
          const at = performance.now(); original.frame.apply(this, args);
          if (n >= warmup) rows.push({ work: performance.now() - started, simulation: simMs,
            drawing: renderMs, renderCpu: cpuRenderMs, submission: submitMs, gpuWait: renderMs - cpuRenderMs,
            isolationOverhead: isolationMs,
            interface: performance.now() - at, shadow: renderer.lastShadowRedraw,
            phases: { ...probes.times }, calls: { ...probes.calls },
            draws: renderer.gl.info.render.calls, triangles: renderer.gl.info.render.triangles });
          if (++n === warmup + samples) { clearTimeout(timeout); resolve(); }
        } catch (error) { fail(error); throw error; }
      };
    });
  } finally {
    game.update = original.update; renderer.draw = original.draw; ui.frame = original.frame;
    renderer.gl.render = original.render; probes.dispose(); renderer.shadowState = null;
    renderer.diagnosticTime = diagnosticTime;
    Math.random = randomBefore;
    game.speed = 0;
  }
  if (gl.getError() !== gl.NO_ERROR) throw new Error('WebGL error in live gameplay');
  const values = key => rows.map(row => row[key]);
  const mean = key => values(key).reduce((a, b) => a + b, 0) / rows.length;
  const phaseLabels = ['daily', 'wildlife', 'plants', 'terrain', 'actors', 'visibility', 'shadowSelection'];
  const phaseSummary = Object.fromEntries(phaseLabels.map(key => {
    const all = rows.map(r => r.phases[key] || 0), active = rows.filter(r => r.calls[key]).map(r => r.phases[key] || 0);
    return [key, { totalMs: all.reduce((a, b) => a + b, 0), p95Ms: percentile(all, .95), activeP95Ms: percentile(active, .95), frames: active.length }];
  }));
  const shadowSummary = Object.fromEntries([false, true].map(refresh => {
    const group = rows.filter(row => row.shadow === refresh);
    return [refresh ? 'refreshed' : 'cached', { frames: group.length, medianMs: percentile(group.map(r => r.drawing), .5), p95Ms: percentile(group.map(r => r.drawing), .95), drawCallsMedian: percentile(group.map(r => r.draws), .5) }];
  }));
  const intervalMeanMs = gaps.reduce((a, b) => a + b, 0) / gaps.length;
  return { ...renderer.perfSample(false), benchmark_revision: PERFORMANCE_BENCHMARK_REVISION, scenario: scene, map, density: density || null, isolation, motion, speed, samples: rows.length, warmup,
    elapsedMs: performance.now() - began, fps: 1000 / intervalMeanMs, intervalMeanMs, intervalP95Ms: percentile(gaps, .95),
    frameMeanMs: mean('work'), frameMedianMs: percentile(values('work'), .5), frameP95Ms: percentile(values('work'), .95), frameMaxMs: Math.max(...values('work')),
    simulationMedianMs: percentile(values('simulation'), .5), simulationP95Ms: percentile(values('simulation'), .95),
    drawingMedianMs: percentile(values('drawing'), .5), drawingP95Ms: percentile(values('drawing'), .95),
    renderCpuP95Ms: percentile(values('renderCpu'), .95), submissionP95Ms: percentile(values('submission'), .95),
    gpuWaitMeanMs: mean('gpuWait'), gpuWaitP95Ms: percentile(values('gpuWait'), .95), interfaceP95Ms: percentile(values('interface'), .95),
    isolationOverheadMedianMs: percentile(values('isolationOverhead'), .5), isolationOverheadP95Ms: percentile(values('isolationOverhead'), .95),
    drawCallsMedian: percentile(values('draws'), .5), drawCallsP95: percentile(values('draws'), .95),
    trianglesMedian: percentile(values('triangles'), .5), trianglesP95: percentile(values('triangles'), .95),
    phases: phaseSummary, shadowFrames: shadowSummary, initial, initialSignature, final: ecosystemCounts(game), finalSignature: ecosystemSignature(game), ...renderObjectCounts(renderer.scene),
    geometries: renderer.gl.info.memory.geometries, textures: renderer.gl.info.memory.textures, animals: game.wildlife.agents.length,
    renderWidth: renderer.gl.domElement.width, renderHeight: renderer.gl.domElement.height,
    slow_frames_pct: Math.round(gaps.filter(ms => ms > 34).length / gaps.length * 100),
    notes: 'FPS includes scheduling and the selected frame cap. Drawing includes gl.finish; GPU wait is a synchronization wait, not a GPU timer. CPU phase times overlap. Isolation modes restore the same starting snapshot; simulation-off then freezes it. Reef shared fruit/buoy dots remain visible.' };
}
